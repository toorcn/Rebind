// Extracts abi + bytecode from forge output into src/chain-artifacts.ts so the
// server and the CLI can deploy and call the contracts without forge installed.
// Run after `forge build`: npm run chain-artifacts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const names = ["DemoUSD", "HumanRegistry", "TwoHumansHook", "ACPCore"];

const entries = names.map((name) => {
  const artifact = JSON.parse(
    readFileSync(join(here, "out", `${name}.sol`, `${name}.json`), "utf8")
  );
  return { name, abi: artifact.abi, bytecode: artifact.bytecode.object };
});

const body = entries
  .map(
    ({ name, abi, bytecode }) =>
      `export const ${name} = {\n  abi: ${JSON.stringify(abi, null, 2)} as const,\n  bytecode: ${JSON.stringify(bytecode)} as \`0x\${string}\`,\n};\n`
  )
  .join("\n");

const header = `// Generated by contracts/gen-artifacts.mjs from contracts/out. Do not edit by hand.\n// Regenerate with: npm run chain-artifacts\n\n`;

writeFileSync(join(here, "..", "src", "chain-artifacts.ts"), header + body);
console.log(`wrote src/chain-artifacts.ts (${entries.length} contracts)`);
